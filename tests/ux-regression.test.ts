function storage() { const data = new Map<string, string>(); return { getItem: (key: string) => data.get(key) ?? null, setItem: (key: string, value: string) => { data.set(key, value); } }; }
test('existing library app is immediately persisted to rest mode without a second app or repeated reference', () => {
  const port = storage(); const settings = freshSettings();
  const app = { id: 'music', name: 'Яндекс Музыка', path: 'C:\\Apps\\Music.exe', useDefaultBrowser: false };
  settings.applications.push(app); const before = structuredClone(settings);
  const rest = settings.modes.find(mode => mode.id === 'rest')!;
  const added = addLibraryAction(settings, rest, app, 'music-action');
  saveSettings(port, added.settings); const loaded = loadSettings(port).settings;
  assert.deepEqual(loaded.applications, before.applications);
  const action = loaded.modes.find(mode => mode.id === 'rest')!.actions.find(action => action.id === 'music-action')!;
  assert.deepEqual(action, { id: 'music-action', kind: 'application', label: '', active: true, applicationId: 'music' });
  assert.equal('path' in action, false); assert.deepEqual(settings, before);
  const repeated = addLibraryAction(loaded, loaded.modes.find(mode => mode.id === 'rest')!, app, 'second');
  assert.deepEqual(repeated.settings, loaded);
});
test('creation inside a mode commits shared item and reference together, also for sites', () => {
  const port = storage(); let settings = freshSettings();
  const app = { id: 'new-app', name: 'Музыка', path: 'D:\\Apps\\Music.exe', useDefaultBrowser: false };
  const first = addLibraryAction(settings, settings.modes[0], app, 'app-action'); saveSettings(port, first.settings);
  settings = loadSettings(port).settings;
  assert.ok(settings.applications.some(item => item.id === app.id));
  assert.ok(settings.modes[0].actions.some(action => action.kind === 'application' && action.applicationId === app.id));
  const site = { id: 'new-site', name: 'Twitch', url: 'https://twitch.tv' };
  const second = addLibraryAction(settings, settings.modes[0], site, 'site-action'); saveSettings(port, second.settings);
  const loaded = loadSettings(port).settings;
  assert.ok(loaded.sites.some(item => item.id === site.id));
  assert.ok(loaded.modes[0].actions.some(action => action.kind === 'site' && action.siteId === site.id && !('url' in action)));
  const snapshot = structuredClone(settings);
  assert.throws(() => saveSettings({ getItem: () => null, setItem: () => { throw new Error('quota'); } }, second.settings));
  assert.deepEqual(settings, snapshot);
});
test('normalized EXE/URL duplicates reuse stable IDs and leave existing user duplicates untouched', () => {
  const settings = freshSettings();
  const app = { id: 'original', name: 'Музыка', path: 'C:\\Apps\\Music.exe', useDefaultBrowser: false };
  settings.applications.push(app);
  const candidate = { ...app, id: 'new', name: 'Другое название', path: 'c:/apps//MUSIC.EXE' };
  assert.equal(duplicateApplication(settings.applications, candidate)?.id, 'original');
  assert.equal(duplicateApplication(settings.applications, { ...candidate, name: '  Музыка ', path: '' })?.id, 'original');
  const result = addLibraryAction(settings, settings.modes[0], candidate, 'new-action');
  assert.equal(result.settings.applications.length, settings.applications.length);
  assert.ok(result.mode.actions.some(action => action.kind === 'application' && action.applicationId === 'original'));
  const site = { id: 'website', name: 'Сайт', url: 'https://EXAMPLE.com:443' }; settings.sites.push(site);
  const equivalent = { id: 'candidate', name: 'Другое имя', url: 'https://example.com/' };
  assert.equal(duplicateSite(settings.sites, equivalent)?.id, 'website');
  const second = addLibraryAction(settings, settings.modes[0], equivalent, 'web-action');
  assert.equal(second.settings.sites.length, settings.sites.length);
  settings.applications.push({ ...app, id: 'old-duplicate' });
  const preserved = addLibraryAction(settings, settings.modes[0], app, 'ref');
  assert.ok(preserved.settings.applications.some(item => item.id === 'old-duplicate'));
});
test('picked EXE creates a saved standalone command executable through the existing router/services', async () => {
  const port = storage(); const settings = freshSettings(); let calls = 0;
  const target = await pickApplicationExe(async () => { calls++; return 'C:\\Apps\\Music.exe'; });
  assert.equal(calls, 1);
  const command: UserCommand = { id: 'music-command', name: 'Открой музыку', phrase: '', kind: 'program', target: target! };
  const library = commandLibrary(settings, command, true, 'music-library');
  saveSettings(port, { ...settings, ...library, commands: [command] });
  const loaded = loadSettings(port).settings;
  assert.deepEqual(routeCommand(command.name, loaded.modes, loaded.commands), { kind: 'action', commandId: command.id });
  const requests: unknown[] = []; const services = createSystemServices(async (kind, target) => { requests.push({ kind, target }); });
  await executeUserCommand(loaded.commands[0], services);
  assert.deepEqual(requests, [{ kind: 'program', target: 'C:\\Apps\\Music.exe' }]);
  assert.equal(loaded.modes.some(mode => mode.actions.some(action => action.kind === 'command' && action.commandId === command.id)), false);
  assert.equal(commandLibrary(loaded, command, true, 'not-a-copy').applications.length, loaded.applications.length);
  assert.equal(await pickApplicationExe(async () => null), null);
  await assert.rejects(pickApplicationExe(async () => 'cmd /c calc.exe'));
  await assert.rejects(pickApplicationExe(async () => { throw new Error('dialog'); }));
});
test('site command optionally joins library without URL copies or changing existing entries', () => {
  const settings = freshSettings(); const command: UserCommand = { id: 'cmd', name: 'Открой сайт', phrase: '', kind: 'website', target: 'https://example.com' };
  assert.equal(commandLibrary(settings, command, false, 'new').sites.length, settings.sites.length);
  const library = commandLibrary(settings, command, true, 'shared-site');
  const next = { ...settings, ...library };
  assert.equal(library.sites.at(-1)?.id, 'shared-site');
  assert.equal(commandLibrary(next, { ...command, target: 'https://EXAMPLE.COM:443/' }, true, 'copy').sites.length, library.sites.length);
  assert.deepEqual(settings.sites, freshSettings().sites);
});
